export UCCL_LITE_MP_PACKET_RS_RETAIN=${UCCL_LITE_MP_PACKET_RS_RETAIN:-1}
export UCCL_LITE_MP_PACKET_AR=1
export UCCL_LITE_MP_PACKET_AR_GPU_MAX_BYTES=${UCCL_LITE_MP_PACKET_AR_GPU_MAX_BYTES:-16384}
export UCCL_LITE_MP_PACKET_SPLIT_CREDITS=1
export UCCL_LITE_MP_PACKET_SCRATCH=${UCCL_LITE_MP_PACKET_SCRATCH:-1}
